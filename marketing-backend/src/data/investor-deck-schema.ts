/* ============================================================
   Investor Deck — placeholder schema (single source of truth)

   Each entry maps one PowerPoint placeholder to:
     • where it appears in the deck (slide # + title + section)
     • the customer-facing question on the website
     • the input widget to render
     • whether it's required
     • the cell metadata the xlsx writer needs

   This file is consumed by THREE clients:
     1. GET /api/customer/deck-schema           → frontend renders form
     2. workers/xlsx-worker.ts                   → writes one row per entry
                                                   into Investor_Deck_Questionnaire_Inputs
     3. The future PPT placeholder-replacer     → looks up Answer_Value
                                                   keyed by Placeholder_Name

   IMPORTANT:
     • Never change `placeholder` once shipped — downstream automation
       relies on exact match.
     • If a placeholder appears on multiple slides (e.g. LEAD_INVESTOR
       on slides 2 and 20), define it ONCE with slideNumbers as an array
       so the Excel sheet has a single source-of-truth row.
   ============================================================ */

export type InvestorDeckInputType =
  | 'shortText'
  | 'longText'
  | 'number'
  | 'year'
  | 'date'
  | 'email'
  | 'image'
  | 'table';

export interface InvestorDeckField {
  /** camelCase key used in formData.investorDeck. Stable. */
  fieldKey: string;
  /** Exact PowerPoint placeholder name, including the {{ }} braces. */
  placeholder: string;
  /** Display section in the questionnaire UI. */
  section: string;
  /** Slide number(s) where this placeholder appears in the deck. */
  slideNumbers: number[];
  /** Slide title (for the Excel sheet's Slide_Title column). */
  slideTitle: string;
  /** Customer-friendly question. */
  question: string;
  /** Input widget type. */
  inputType: InvestorDeckInputType;
  /** Whether the questionnaire enforces a value. */
  required: boolean;
  /** Helper text shown under the field. */
  guidance: string;
  /** Why this matters for the deck (goes into Purpose_in_Investor_Deck column). */
  purpose: string;
  /** Optional notes column (mostly empty). */
  notes?: string;
}

